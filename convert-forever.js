// Converts forever-professions.json / forever-mats.json into a Lua table for the CraftCalcForever addon.
// Usage: node convert-forever.js            (writes to every Forever install found below)
//        node convert-forever.js <addonDir> (writes to that folder instead)
// Output: CraftCalcForever_Data.lua

const fs   = require('fs');
const path = require('path');

const WOW_DIR     = 'D:\\World of Warcraft';
const INSTALLS    = ['_forever_', '_classic_beta_'];   // live folder name is a guess until launch
const ADDON_NAME  = 'CraftCalcForever';
const GAME_DIR    = __dirname;

const PROF_NAMES = {
  129: 'First Aid',
  164: 'Blacksmithing',
  165: 'Leatherworking',
  171: 'Alchemy',
  185: 'Cooking',
  186: 'Mining',
  197: 'Tailoring',
  202: 'Engineering',
  333: 'Enchanting',
};

function load(file) {
  return JSON.parse(fs.readFileSync(path.join(GAME_DIR, file), 'utf8'));
}

function esc(s) {
  return (s || '').replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

const profs = load('forever-professions.json');
const mats  = load('forever-mats.json');

const itemsById = {};
for (const item of mats) itemsById[item.id] = item;

// Recipes without an output item (enchants, campsite objects) use negative spell ID as output ID
const recipes = [];
for (const r of profs) {
  if (!r.reagents?.length) continue;
  let outputId, makes;
  if (r.creates?.item_id) {
    outputId = r.creates.item_id;
    makes    = r.creates.item_count || 1;
  } else {
    outputId = -r.id;
    makes    = 1;
    itemsById[outputId] = { id: outputId, name: r.name, icon: r.icon || '' };
  }
  recipes.push({ ...r, _outputId: outputId, _makes: makes });
}

// Recipe categories in the order the profession window lists them; uncategorised ones go last
const categories = [];
const catIndex   = {};
for (const r of recipes) {
  const name = r.category || 'Miscellaneous';
  if (!(name in catIndex)) {
    catIndex[name] = categories.length + 1;
    categories.push({ name, order: r.category_order ?? 1e6 });
  } else if (r.category_order != null) {
    const c = categories[catIndex[name] - 1];
    c.order = Math.min(c.order, r.category_order);
  }
}

// Build Lua
let out = '-- Auto-generated by convert-forever.js — do not edit manually\n';
out += `-- ${recipes.length} recipes | ${Object.keys(itemsById).length} items\n\n`;

// CraftCalcForeverCategories: [index] = {"Name", sortOrder}
out += 'CraftCalcForeverCategories = {\n';
for (const c of categories) out += `  {"${esc(c.name)}",${c.order}},\n`;
out += '}\n\n';

// CraftCalcForeverRecipes: {outputItemId, makes, "ProfName", "RecipeName", {{reagId,count},...}, spellId,
//                           categoryIndex, {learnedAt, yellow, green, grey}}
out += 'CraftCalcForeverRecipes = {\n';
for (const r of recipes) {
  const prof   = esc(PROF_NAMES[r.type] || 'Unknown');
  const reags  = r.reagents.map(rg => `{${rg.item_id},${rg.item_count}}`).join(',');
  const levels = [r.learned_at_rank, r.color_level_2, r.color_level_3, r.color_level_4].map(n => n ?? 0).join(',');
  out += `  {${r._outputId},${r._makes},"${prof}","${esc(r.name)}",{${reags}},${r.id},${catIndex[r.category || 'Miscellaneous']},{${levels}}},\n`;
}
out += '}\n\n';

// CraftCalcForeverItems: [id] = {"Name", "icon_slug", raw, quality}
//   raw = never expand: gathered (skinning/node), disenchanted, or a conversion pair
out += 'CraftCalcForeverItems = {\n';
for (const [id, item] of Object.entries(itemsById)) {
  const raw = item.raw || (item.sources || []).some(s => s.type === 1 || s.type === 8 || s.type === 11);
  out += `  [${id}]={"${esc(item.name || '')}","${esc(item.icon || '')}",${raw ? 'true' : 'false'},${item.quality ?? 1}},\n`;
}
out += '}\n';

const targets = process.argv[2]
  ? [process.argv[2]]
  : INSTALLS.map(d => path.join(WOW_DIR, d)).filter(fs.existsSync)
            .map(d => path.join(d, 'Interface', 'AddOns', ADDON_NAME));
if (!targets.length) {
  console.error(`No Forever install found under ${WOW_DIR} — pass the addon folder as an argument.`);
  process.exit(1);
}

for (const dir of targets) {
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `${ADDON_NAME}_Data.lua`), out, 'utf8');
}

console.log('Done!');
console.log(`  Recipes : ${recipes.length} in ${categories.length} categories`);
console.log(`  Items   : ${Object.keys(itemsById).length}`);
console.log(`  Size    : ${(Buffer.byteLength(out, 'utf8') / 1024).toFixed(1)} KB`);
targets.forEach(t => console.log(`  Output  : ${path.join(t, `${ADDON_NAME}_Data.lua`)}`));
